pub fn app_font(lang: &Language) -> Font {
    match lang {
        Language::Ar => Font {
            family: Family::Name("Reem Kufi"),
            weight: Weight::Normal,
            stretch: Stretch::Normal,
            style: Style::Normal,
        },
        _ => Font {
            family: Family::Name("Cinzel"),
            weight: Weight::Normal,
            stretch: Stretch::Normal,
            style: Style::Normal,
        },
    }
}

